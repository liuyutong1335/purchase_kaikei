  // API 連携状態の導出: kaikeiEntryId が付いた = 連携済み、Outbox キューに残っている = 未連携、
  // 業務エラーで破棄された = エラー（ステップ 10 で専用画面を作る。ここでは状態判定のみ）
  #linkState(entry) {
    if (entry.kaikeiEntryId != null) return 'linked';
    if (this.data.lastLinkError && this.data.lastLinkError.localEntryId === entry.id) return 'error';
    if (this.data.pendingLinks.some((pl) => pl.localEntryId === entry.id)) return 'unlinked';
    return 'unlinked';
  }

  listEntries({ from, to, account, department, q, state: linkState } = {}) {
    const accountNames = new Map(ACCOUNTS_MASTER_LIST.map((a) => [a.code, a.name]));
    return this.data.entries
      .filter((e) => {
        if (from && e.date < from) return false;
        if (to && e.date > to) return false;
        if (department && e.department !== department) return false;
        if (account && !e.lines.some((l) => l.account_code === account)) return false;
        if (q && !(`${e.id} ${e.description} ${e.purchaseId || ''} ${e.voucherNo || ''}`.includes(q))) return false;
        return true;
      })
      .filter((e) => (linkState ? this.#linkState(e) === linkState : true))
      .map((e) => {
        const debit = e.lines.find((l) => l.side === 'debit');
        const credit = e.lines.find((l) => l.side === 'credit');
        return {
          id: e.id,
          date: e.date,
          voucherNo: e.voucherNo || null,
          purchaseId: e.purchaseId || null,
          vendor: e.purchaseId
            ? (() => {
                const p = this.data.purchases.find((x) => x.id === e.purchaseId);
                if (!p || !p.vendorCode) return null;
                const v = (this.data.vendors || []).find((vv) => vv.code === p.vendorCode);
                return v ? `${v.code} ${v.name}` : p.vendorCode;
              })()
            : null,
          description: e.description,
          debitAccount: debit ? `${debit.account_code} ${accountNames.get(debit.account_code) || ''}` : null,
          creditAccount: credit ? `${credit.account_code} ${accountNames.get(credit.account_code) || ''}` : null,
          amount: e.lines.filter((l) => l.side === 'debit').reduce((s, l) => s + l.amount, 0),
          multiLine: e.lines.length > 2,
          lines: e.lines.map((l) => ({ ...l })),
          status: e.status || 'active',
          entryType: e.entryType || 'normal',
          reversesEntryId: e.reversesEntryId ?? null,
          reversedBy: e.reversedBy ?? null,
          postedBy: e.postedBy || null,
          linkState: this.#linkState(e),
          createdAt: e.createdAt,
        };
      });
  }

