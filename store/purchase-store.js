  create({ item, qty, unitPrice, requester, department, note, vendorCode, itemCode }) {
    if (!item || typeof item !== 'string' || !item.trim()) {
      throw new ValidationError('item is required');
    }
    if (!Number.isInteger(qty) || qty < 1) {
      throw new ValidationError('qty must be an integer >= 1');
    }
    if (typeof unitPrice !== 'number' || unitPrice < 0 || Number.isNaN(unitPrice)) {
      throw new ValidationError('unitPrice must be a number >= 0');
    }
    if (!requester || typeof requester !== 'string' || !requester.trim()) {
      throw new ValidationError('requester is required');
    }
    // v6 ステップ 1: 申請者はユーザーマスタのコードで受ける（表記揺れ防止）
    const requesterUser = (this.data.users || []).find((u) => u.code === requester.trim() && u.active);
    if (!requesterUser) {
      throw new ValidationError(`unknown requester: ${requester}`);
    }
    // v6 ステップ 8: 仕入先・品目はマスタのコードで受ける（指定時のみ検証。UI は選択必須）
    let vendor = null;
    if (vendorCode != null && vendorCode !== '') {
      vendor = (this.data.vendors || []).find((v) => v.code === vendorCode);
      if (!vendor) throw new ValidationError(`unknown vendor: ${vendorCode}`);
    }
    let itemMaster = null;
    if (itemCode != null && itemCode !== '') {
      itemMaster = (this.data.items || []).find((i) => i.code === itemCode);
      if (!itemMaster) throw new ValidationError(`unknown item: ${itemCode}`);
    }
    if (department != null && !DEPARTMENTS.includes(department)) {
      throw new ValidationError(`department must be one of ${DEPARTMENTS.join('/')}`);
    }
    this.data.counters.purchase += 1;
    const id = `PU-${String(this.data.counters.purchase).padStart(4, '0')}`;
    const purchase = {
      id,
      item: item.trim(),
      qty,
      unitPrice,
      amount: qty * unitPrice,
      requester: requesterUser.code, // ユーザーコードで保存（表示名は listUsers 解決）
      vendorCode: vendor ? vendor.code : null,
      itemCode: itemMaster ? itemMaster.code : null,
      department: department || 'D90', // AC-001-02: 既定 D90（管理部・共通）
      note: note || '',
      status: 'submitted',
      orderNo: null,
      receivedTotal: 0,
      journal: [], // 仕訳参照: { kind, entryId, qty?, amount, date }（NFR-003）
      createdAt: now(),
      history: [
        { from: null, to: 'submitted', at: now(), actor: requesterUser.code, comment: '購買申請登録' },
      ],
    };
    this.data.purchases.push(purchase);
    return this.#save().then(() => purchase);
  }

