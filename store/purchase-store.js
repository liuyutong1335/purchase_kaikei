  // 申請日などの履歴から日付を取り出す（YYYY-MM-DD 部分のみ比較に使う）
  #dateOf(purchase, toStatus, fromStatus = null) {
    const h = purchase.history.find((h) => h.to === toStatus && (fromStatus == null || h.from === fromStatus || h.from === null || h.from === h.to));
    return h ? h.at.slice(0, 10) : null;
  }

  // 購買 1 件を一覧表示用に拡張する（申請日・発注日・検収日・支払予定日を派生）
  #enrichPurchase(p) {
    const relatedPayables = this.data.payables.filter((y) => y.purchaseId === p.id);
    const scheduled = relatedPayables.filter((y) => y.status === 'scheduled').map((y) => y.scheduledDate).sort();
    const receiveEvents = p.history.filter((h) => h.receivedAt != null);
    const relatedPayablesAll = relatedPayables.filter((y) => y.receivedDate);
    const vendor = p.vendorCode ? (this.data.vendors || []).find((v) => v.code === p.vendorCode) : null;
    return {
      ...p,
      requestedDate: (p.createdAt || '').slice(0, 10),
      orderDate: this.#dateOf(p, 'ordered'),
      receiveDate: relatedPayablesAll.length > 0
        ? relatedPayablesAll[relatedPayablesAll.length - 1].receivedDate
        : (receiveEvents.length > 0 ? receiveEvents[receiveEvents.length - 1].receivedAt : null),
      scheduledDate: scheduled[0] || null,
      vendorCode: p.vendorCode || null,
      vendorName: vendor ? vendor.name : null,
    };
  }

  // v6 ステップ 6: 購買一覧の複合検索
  listPurchases({ q, requester, department, vendor, item, status, requestedFrom, requestedTo, orderFrom, orderTo, receiveFrom, receiveTo, scheduledFrom, scheduledTo } = {}) {
    return this.data.purchases
      .filter((p) => {
        if (status && p.status !== status) return false;
        if (requester && p.requester !== requester) return false;
        if (department && p.department !== department) return false;
        if (vendor && p.vendorCode !== vendor) return false;
        if (item && !(p.item || '').includes(item)) return false;
        if (q && !`${p.id} ${p.item} ${p.note || ''} ${p.orderNo || ''}`.includes(q)) return false;
        return true;
      })
      .map((p) => this.#enrichPurchase(p))
      .filter((e) => {
        if (requestedFrom && (!e.requestedDate || e.requestedDate < requestedFrom)) return false;
        if (requestedTo && (!e.requestedDate || e.requestedDate > requestedTo)) return false;
        if (orderFrom && (!e.orderDate || e.orderDate < orderFrom)) return false;
        if (orderTo && (!e.orderDate || e.orderDate > orderTo)) return false;
        if (receiveFrom && (!e.receiveDate || e.receiveDate < receiveFrom)) return false;
        if (receiveTo && (!e.receiveDate || e.receiveDate > receiveTo)) return false;
        if (scheduledFrom && (!e.scheduledDate || e.scheduledDate < scheduledFrom)) return false;
        if (scheduledTo && (!e.scheduledDate || e.scheduledDate > scheduledTo)) return false;
        return true;
      });
  }

